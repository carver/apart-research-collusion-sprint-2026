DRAFT_NAME = "DRAFT-paper"
FINAL_NAME = "zerocommcartel"  # the submission: <paper dir>/zerocommcartel.pdf and its ledger


@dataclass
class Report:
    pdf: Path | None  # None when a final build fails: no unmarked PDF is written then
    pages: list[Path]
    body_pages: int | None
    abstract: str
    abstract_words: int
    todos: int
    missing: list[str]
    failed_claims: list[str]
    unreferenced: list[str]
    missing_sections: list[str]
    size: int
    changed: list[str]  # the ledger's entries that changed since the last build
    problems: list[Problem] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)  # a draft and a final build both print them


_reading: list[set[str]] = []  # the .jsonl files the running data source has opened


def _record_reads(event: str, args: tuple[Any, ...]) -> None:
    if event == "open" and _reading and isinstance(args[0], str | os.PathLike):
        path, mode = os.fspath(args[0]), args[1]
        if str(path).endswith(".jsonl") and (mode is None or "r" in str(mode)):
            _reading[-1].add(os.path.abspath(path))


sys.addaudithook(_record_reads)  # audit hooks can't be removed; this one records only while a source runs


def fill(sources: Mapping[str, Source], figures: Path, repo: Repo | None) -> tuple[Ledger, list[Problem]]:
    """Runs each source into a ledger of its own and merges them, each entry stamped with its source and the
    logs it read. A source that fails, or claims a key another has, adds nothing and is a problem."""
    ledger, problems = Ledger(figures), []
    for name, function in sources.items():
        part = Ledger(figures)
        _reading.append(set())
        try:
            function(part)
        except Exception as error:
            problems.append(Problem("source", f"{name}: {type(error).__name__}: {error}"))
            continue
        finally:
            read = _reading.pop()
        logs = tuple(sorted(repo.relative(path) if repo else path for path in read))
        try:
            ledger.merge(part, Provenance(function.__module__, function.__qualname__, logs))
        except DuplicateKey as error:
            problems.append(Problem("source", f"{name}: {error}"))
    return ledger, problems


def changes(before: dict[str, dict], after: dict[str, dict]) -> list[str]:
    """What changed in the ledger, one line per key."""
    lines = [f"{key}: new, {display(after[key])}" for key in sorted(after.keys() - before.keys())]
    lines += [f"{key}: gone" for key in sorted(before.keys() - after.keys())]
    for key in sorted(before.keys() & after.keys()):
        old, new = before[key], after[key]
        if {**old, "source": None} != {**new, "source": None}:
            shown = (display(old), display(new))
            lines.append(f"{key}: {shown[0]} → {shown[1]}" if shown[0] != shown[1] else f"{key}: changed")
    return lines


def markdown(entries: dict[str, dict]) -> str:
    lines = [
        "# The ledger",
        "",
        "Every key paper.typ can cite (paper/lib.typ's #n, #pct, #ci, #claim, #data-table, #data-figure and",
        "#data-text), from the last build. Generated by bin/build-paper; don't edit.",
        "",
        "| key | kind | value | how | source |",
        "|---|---|---|---|---|",
    ]
    for key, entry in sorted(entries.items()):
        source = entry["source"]
        origin = f"{source['module']}.{source['function']}" + "".join(f" {log}" for log in source["logs"])
        lines.append(f"| {key} | {entry['kind']} | {display(entry)} | {entry['how']} | {origin} |")
    for key, entry in sorted(entries.items()):
        if entry["kind"] == "table":
            lines += ["", f"## {key}", "", _row(entry["header"]), "|---" * len(entry["header"]) + "|"]
            lines += [_row(row) for row in entry["rows"]]
    return "\n".join(lines) + "\n"


def _row(cells: list[str]) -> str:
    """A markdown table row, with a | or a line break inside a cell escaped so it can't split the row."""
    return "| " + " | ".join(cell.replace("|", "\\|").replace("\n", " ") for cell in cells) + " |"


def write_atomic(path: Path, data: bytes) -> None:
    """Writes `path` through a temporary file beside it, so a reader (a PDF viewer) never sees half of it."""
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=f".{path.name}.", delete=False) as temp:
        try:
            temp.write(data)
            temp.flush()
            umask = os.umask(0)
            os.umask(umask)
            os.chmod(temp.name, 0o666 & ~umask)  # a temporary file is private; the PDF isn't
            os.replace(temp.name, path)
        except BaseException:
            os.unlink(temp.name)
            raise


def stamp(repo: Repo | None) -> str:
    """The draft footer's line: the commit, and when the build ran."""
    built = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    if repo is None:
        return f"not in git · built {built}"
    dirty = " with uncommitted changes" if repo.dirty() else ""
    return f"commit {repo.head()[:7]}{dirty} · built {built}"


def write_pages(folder: Path, pngs: list[bytes]) -> list[Path]:
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    pages = [folder / f"page-{number:02}.png" for number in range(1, len(pngs) + 1)]
    for page, png in zip(pages, pngs, strict=True):
        page.write_bytes(png)
    return pages


LOCK = ".lock"  # in build/: held by the build that is running, with its pid inside


@contextmanager
def build_lock(out: Path) -> Iterator[None]:
    """Holds <out>/.lock for a build, after waiting for any other build of the same paper to finish. The OS
    drops the lock when its process ends, so a crashed build leaves none behind."""
    out.mkdir(parents=True, exist_ok=True)
    with os.fdopen(os.open(out / LOCK, os.O_RDWR | os.O_CREAT, 0o644), "r+") as lock:
        if not _try_lock(lock):
            pid = _read_pid(lock)
            holder = f"pid {pid}" if pid else "pid unknown"
            print(f"build-paper: waiting for another build of this paper ({holder})", file=sys.stderr)
            fcntl.flock(lock, fcntl.LOCK_EX)
        lock.seek(0)
        lock.truncate()
        lock.write(str(os.getpid()))
        lock.flush()
        yield


def lock_holder(out: Path) -> int | None:
    """The pid of the process holding <out>/.lock, or None when no build runs (or, for an instant, when the
    one that just took it hasn't written its pid yet)."""
    if not (out / LOCK).exists():
        return None
    with (out / LOCK).open("a+") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return _read_pid(lock)
        fcntl.flock(lock, fcntl.LOCK_UN)
        return None


def _try_lock(lock: IO[str]) -> bool:
    """Takes the lock if it is free. Tries a few times over 50 ms, since lock_holder() takes it for an
    instant to see whether it is free."""
    for _ in range(5):
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            return True
        except BlockingIOError:
            time.sleep(0.01)
    return False


def _read_pid(lock: IO[str]) -> int | None:
    lock.seek(0)
    text = lock.read().strip()
    return int(text) if text.isdigit() else None


def build(paper_dir: Path, sources: Mapping[str, Source] | None = None, final: bool = False) -> Report:
    """Builds <paper_dir>/paper.typ from `sources` (every registered data source by default), once no other
    build of it runs. Raises BuildError when Typst can't compile it; every other problem is in the report."""
    with build_lock(paper_dir / "build"):
        return _build(paper_dir, sources, final)


def _build(paper_dir: Path, sources: Mapping[str, Source] | None, final: bool) -> Report:
    out, repo = paper_dir / "build", Repo.of(paper_dir)
    shutil.rmtree(out / "figures", ignore_errors=True)
    ledger, problems = fill(registered() if sources is None else sources, out / "figures", repo)
    numbers, built = out / "numbers.json", out / "numbers-built.json"  # built: the last build that compiled
    out.mkdir(parents=True, exist_ok=True)
    numbers.write_text(json.dumps(ledger.entries, indent=1, ensure_ascii=False) + "\n")
    (out / "numbers.md").write_text(markdown(ledger.entries))

    inputs = {
        "draft": "false" if final else "true",
        "stamp": stamp(repo),
        "commit": repo.head() if repo else "",
    }
    page = typeset(paper_dir, inputs)
    changed = changes(json.loads(built.read_text()) if built.exists() else {}, ledger.entries)
    (out / "changes.md").write_text(
        "# Changes since the last build\n\n" + "".join(f"- {c}\n" for c in changed)
    )
    shutil.copy(numbers, built)
    paper_text = (paper_dir / "paper.typ").read_text()
    problems += rules(page) + swallowed_semicolons(paper_text) + swallowed_hashes(paper_text)
    if final:
        logs = sorted({log for entry in ledger.entries.values() for log in entry["source"]["logs"]})
        problems += broken_links(page) + unshipped(repo, logs)

    pdf = None
    if not final:
        pdf = out / f"{DRAFT_NAME}.pdf"
    elif not problems:
        pdf = paper_dir / f"{FINAL_NAME}.pdf"
        shutil.copy(numbers, paper_dir / f"{FINAL_NAME}-numbers.json")
    if pdf:
        write_atomic(pdf, page.pdf)
    return Report(
        pdf=pdf,
        pages=write_pages(out / "pages", page.pngs),
        body_pages=body_pages(page),
        abstract=page.abstract,
        abstract_words=len(page.abstract.split()),
        todos=page.todos,
        missing=page.missing,
        failed_claims=failed_claims(page),
        unreferenced=unreferenced(page),
        missing_sections=missing_sections(page),
        size=len(page.pdf),
        changed=changed,
        problems=problems,
        warnings=unclaimed_wording(paper_text),
    )
